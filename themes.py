def build_universe():
    """테마 목록을 종목 단위 표로 펼친다. 같은 종목이 여러 테마에 있으면 테마를 합친다."""
    rows = {}
    for theme, spec in THEMES.items():
        for country in ("KR", "US"):
            for code, name, market in spec.get(country, []):
                key = (country, code)
                if key not in rows:
                    rows[key] = {
                        "country": country,
                        "code": code,
                        "name": name,
                        "market": market,
                        "themes": [],
                    }
                if theme not in rows[key]["themes"]:
                    rows[key]["themes"].append(theme)
    return list(rows.values())


def yf_symbol(row):
    """야후 파이낸스용 심볼로 변환 (005930 -> 005930.KS)."""
    if row["country"] == "KR":
        return f'{row["code"]}.{row["market"]}'
    return row["code"]
